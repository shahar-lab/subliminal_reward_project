"""Builds the two Pavlovia projects (Day 1 and Day 2) from this one source folder.

    python online/tools/build_pavlovia.py                  -> online/build/<project>-day1, -day2
    python online/tools/build_pavlovia.py --out ../pav     -> into another folder (e.g. next to your Pavlovia clones)

Each output folder is a complete experiment with the day FIXED (js/day.js: FIXED_DAY = 1 or 2), so the
?day= URL parameter is ignored there. Always edit the code in online/ (the single source) and rebuild; never
edit the built folders by hand.

If an output folder is already a git clone of the Pavlovia project, it is updated in place, file by file:
changed files are overwritten and files no longer in the source are removed, EXCEPT inside .git/ and data/
(the participants' results on Pavlovia are never touched). Folders are never deleted and recreated, so it also
works inside OneDrive. Then commit and push from that folder (commands printed at the end).
"""
import argparse
import os
import stat
import time

SRC = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
PROJECT = 'subliminal-reward-pilot'                      # Pavlovia projects: <PROJECT>-day1, <PROJECT>-day2
GROUP = 'Shahar_Lab'
INCLUDE = ['index.html', 'css', 'js', 'jspsych', 'stimuli', 'vendor']   # what the experiment needs
KEEP = {'.git', 'data'}                                  # never deleted in an existing clone

DAY_JS = """// ─── day.js ── GENERATED by online/tools/build_pavlovia.py - do not edit (edit the source in online/).
// This Pavlovia project always runs Day {day}; the ?day= URL parameter is ignored.
var FIXED_DAY = {day};
"""

README = """# {name}

Day {day} of the online pilot of the subliminal reward learning experiment (Shahar lab).

**Do not edit this repository by hand.** It is GENERATED from the `online/` folder of
https://github.com/shahar-lab/subliminal_reward_project by `online/tools/build_pavlovia.py`.
Change the code there, rebuild, then commit and push here. The day is fixed in `js/day.js`.

Prolific study URL:
https://run.pavlovia.org/{group}/{name}/?PROLIFIC_PID={{{{%PROLIFIC_PID%}}}}&STUDY_ID={{{{%STUDY_ID%}}}}&SESSION_ID={{{{%SESSION_ID%}}}}
"""


def _retry(action, path, tries=5):
    """Run action(path); on Windows/OneDrive a file can be briefly locked or read-only: make it writable and retry."""
    for attempt in range(tries):
        try:
            return action(path)
        except PermissionError:
            if attempt == tries - 1:
                raise
            try:
                os.chmod(path, stat.S_IWRITE | stat.S_IREAD)
            except OSError:
                pass
            time.sleep(0.5 * (attempt + 1))


def _write_if_changed(path, data):
    if os.path.exists(path):
        with open(path, 'rb') as f:
            if f.read() == data:
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)

    def write(p):
        with open(p, 'wb') as f:
            f.write(data)
    _retry(write, path)


def build(out_dir, day):
    """Sync the project folder file by file (no folder is deleted and recreated - that fails on OneDrive).
    Files that changed are overwritten, files that are no longer in the source are removed; .git/ and data/
    are never touched."""
    name = f'{PROJECT}-day{day}'
    target = os.path.join(out_dir, name)
    os.makedirs(target, exist_ok=True)

    wanted = {}                                           # relative path -> file content
    for entry in INCLUDE:
        src = os.path.join(SRC, entry)
        if os.path.isdir(src):
            for root, _, files in os.walk(src):
                for fn in files:
                    full = os.path.join(root, fn)
                    with open(full, 'rb') as f:
                        wanted[os.path.relpath(full, SRC)] = f.read()
        else:
            with open(src, 'rb') as f:
                wanted[entry] = f.read()
    wanted[os.path.join('js', 'day.js')] = DAY_JS.format(day=day).encode('utf-8')
    wanted['README.md'] = README.format(name=name, day=day, group=GROUP).encode('utf-8')
    wanted['.gitignore'] = b'.DS_Store\n'

    # remove files that are no longer part of the experiment (outside .git/ and data/)
    for root, dirs, files in os.walk(target, topdown=True):
        if os.path.abspath(root) == os.path.abspath(target):
            dirs[:] = [d for d in dirs if d not in KEEP]
        for fn in files:
            full = os.path.join(root, fn)
            if os.path.relpath(full, target) not in wanted:
                _retry(os.remove, full)
    for root, dirs, files in os.walk(target, topdown=False):     # empty folders: best effort only
        if os.path.relpath(root, target).split(os.sep)[0] in KEEP or os.path.abspath(root) == os.path.abspath(target):
            continue
        if not os.listdir(root):
            try:
                os.rmdir(root)
            except OSError:
                pass

    for rel, data in wanted.items():
        _write_if_changed(os.path.join(target, rel), data)
    return name, target


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', default=os.path.join(SRC, 'build'), help='output folder (default: online/build)')
    args = parser.parse_args()
    out_dir = os.path.abspath(args.out)
    for day in (1, 2):
        name, target = build(out_dir, day)
        fresh = not os.path.isdir(os.path.join(target, '.git'))
        print(f'\nDay {day}: {target}')
        if fresh:
            print(f'  first time: create the project {GROUP}/{name} on gitlab.pavlovia.org, then:')
            print(f'    cd "{target}"')
            print('    git init -b master && git add -A && git commit -m "Online pilot"')
            print(f'    git remote add origin https://gitlab.pavlovia.org/{GROUP}/{name}.git')
            print('    git push -u origin master')
        else:
            print('  existing clone updated (.git and data/ kept); now:')
            print(f'    cd "{target}" && git add -A && git commit -m "Update from GitHub online/" && git push')


if __name__ == '__main__':
    main()
